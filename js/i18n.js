var Lang = (function () {
  var KEY = "groagri-lang";
  var current = "en";
  var listeners = [];

  function read() {
    try {
      var q = new URLSearchParams(location.search).get("lang");
      if (q === "ta" || q === "en") return q;
      var s = localStorage.getItem(KEY);
      if (s === "ta" || s === "en") return s;
    } catch (e) {}
    return "en";
  }

  function t(key, vars) {
    var s = (I18N[current] && I18N[current][key]) || I18N.en[key] || key;
    if (vars) for (var k in vars) s = s.replace("{" + k + "}", vars[k]);
    return s;
  }

  /* pick a {en, ta} object */
  function pick(obj) { return obj ? (obj[current] || obj.en) : ""; }

  function apply(root) {
    root = root || document;
    root.querySelectorAll("[data-i18n]").forEach(function (el) { el.textContent = t(el.getAttribute("data-i18n")); });
    root.querySelectorAll("[data-i18n-html]").forEach(function (el) { el.innerHTML = t(el.getAttribute("data-i18n-html")); });
    root.querySelectorAll("[data-i18n-ph]").forEach(function (el) { el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph"))); });
    root.querySelectorAll("[data-i18n-aria]").forEach(function (el) { el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria"))); });
  }

  function set(lang, silent) {
    current = lang === "ta" ? "ta" : "en";
    try { localStorage.setItem(KEY, current); } catch (e) {}
    document.documentElement.lang = current;
    document.documentElement.setAttribute("data-lang", current);
    var tk = document.body && document.body.getAttribute("data-title");
    if (tk) document.title = t(tk);
    apply();
    document.querySelectorAll(".lang-switch button").forEach(function (b) {
      b.setAttribute("aria-pressed", b.getAttribute("data-lang") === current ? "true" : "false");
    });
    if (!silent) listeners.forEach(function (fn) { fn(current); });
  }

  current = read();
  document.documentElement.lang = current;
  document.documentElement.setAttribute("data-lang", current);

  return {
    t: t, pick: pick, apply: apply, set: set,
    get: function () { return current; },
    on: function (fn) { listeners.push(fn); }
  };
})();
